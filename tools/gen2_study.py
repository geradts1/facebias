"""
Generator comparison: the same 1,008 descriptions generated by Qwen-Image-2512 (main set, the twin
sources) and by FLUX.2 [klein] 4B (data/gen2_flux2klein_full, ids fk_<source id>).

For both sets, with the same pair design and the same recognisers:
  mated      : reference vs every other image of the same person
  non-mated  : reference vs the images of all (max 40) other persons of the same ancestry and gender
Per set, recogniser and condition class (passfoto, edit_hq, cctv_still; FLUX has no video):
  threshold at FMR 1e-3 and 1e-2 over all non-mated pairs (1e-2: more false matches per group, steadier ratios) -> FMR per ancestry (cluster bootstrap 95% CI)
  LR: logistic calibration, one global vs one per ancestry -> mean log10 LR shift of mated pairs
  (relative to the group mean); spread = highest minus lowest group.
Subsets: all 1,008 persons, and the 593 persons FLUX kept after near-duplicate removal (same
persons in both sets), so look-alikes cannot explain the difference.

    python tools/gen2_study.py --flux data/gen2_flux2klein_full
Output: results_extended/gen2_comparison.md / .csv
"""
from __future__ import annotations

import argparse
import json
import shutil
import sys
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "tools"))
import extended_study as es  # noqa: E402
from twins_study import parse_condition, boot_mean  # noqa: E402

OUT = ROOT / "results_extended"
EMB_G = ROOT / "data/embeddings_gen2"
CLS = ["passfoto", "edit_hq", "cctv_still"]


def flux_index(flux: Path, cache: Path) -> pd.DataFrame:
    f = cache / "image_index.csv"
    if f.exists():
        return pd.read_csv(f)
    kept = set(pd.read_csv(flux / "metadata.csv", usecols=["identity_id"], low_memory=False).identity_id)
    rows = []
    for jf in sorted((flux / "identities").glob("*/identity.json")):
        rec = json.loads(jf.read_text())
        if rec.get("status") != "done":
            continue
        for p in sorted(jf.parent.glob("SYNTH_*.png")):
            rows.append({"file": p.name, "path": str(p), "identity_id": rec["identity_id"],
                         "source_id": rec["attrs"].get("twin_of"), "kept": rec["identity_id"] in kept,
                         "condition": parse_condition(p.name), "set": "flux"})
    idx = pd.DataFrame(rows)
    cache.mkdir(parents=True, exist_ok=True)
    idx.to_csv(f, index=False)
    es.log(f"flux: {idx.identity_id.nunique()} persons, {len(idx)} images")
    return idx


def make_pairs(images: pd.DataFrame, attrs: pd.DataFrame, seed=0, k=40) -> pd.DataFrame:
    """images: file, person (= source id), condition. attrs indexed by person: ancestry, gender_presentation."""
    rng = np.random.default_rng(seed)
    refs = images[images.condition == "reference"].drop_duplicates("person").set_index("person").file
    probes = images[images.condition != "reference"]
    by_person = {p: g for p, g in probes.groupby("person")}
    rows = []
    persons = [p for p in refs.index if p in attrs.index]
    strata = attrs.loc[persons].groupby(["ancestry", "gender_presentation"]).groups
    for p in persons:
        g = by_person.get(p)
        if g is not None:
            rows += [(p, p, refs[p], f, c, 1) for f, c in zip(g.file, g.condition)]
        a = attrs.loc[p]
        others = [q for q in strata[(a.ancestry, a.gender_presentation)] if q != p and q in by_person]
        for q in rng.choice(others, size=min(k, len(others)), replace=False) if others else []:
            gq = by_person[q]
            rows += [(p, q, refs[p], f, c, 0) for f, c in zip(gq.file, gq.condition)]
    P = pd.DataFrame(rows, columns=["person_a", "person_b", "file_a", "file_b", "condition", "mated"])
    P["cls"] = es.condition_class(P.condition)
    P = P[P.cls.isin(CLS)].copy()
    P["ancestry"] = P.person_a.map(attrs.ancestry)
    return P


def score(P, idx_map, E, ok):
    ia, ib = P.file_a.map(idx_map), P.file_b.map(idx_map)
    s = np.full(len(P), np.nan)
    have = (ia.notna() & ib.notna()).values
    a, b = ia[have].astype(int).values, ib[have].astype(int).values
    v = np.where(ok[a] & ok[b], (E[a] * E[b]).sum(1), np.nan)
    s[have] = v
    return s


def analyse(P, s, label, matcher, rows):
    from sklearn.linear_model import LogisticRegression
    from facebias.bias import threshold_at_fmr
    P = P.assign(score=s).dropna(subset=["score"])
    for cls in CLS:
        d = P[P.cls == cls]
        if d.mated.nunique() < 2 or (d.mated == 0).sum() < 1000:
            continue
        nm = d[d.mated == 0]
        glob = LogisticRegression(max_iter=500).fit(d[["score"]].values, d.mated.values)
        shifts = {}
        for g, dg in d.groupby("ancestry"):
            if dg.mated.nunique() < 2:
                continue
            spec = LogisticRegression(max_iter=500).fit(dg[["score"]].values, dg.mated.values)
            m = dg[dg.mated == 1][["score"]].values
            # log odds difference, prior terms cancel in the relative shift
            shifts[g] = float(np.mean(glob.decision_function(m) - spec.decision_function(m)
                                      - (np.log(d.mated.mean() / (1 - d.mated.mean()))
                                         - np.log(dg.mated.mean() / (1 - dg.mated.mean())))) / np.log(10))
        mean_shift = np.mean(list(shifts.values())) if shifts else np.nan
        for target in (1e-3, 1e-2):
            thr = threshold_at_fmr(d.score, d.mated, target)
            fnmr = float((d[d.mated == 1].score < thr).mean())
            fmr_all = float((nm.score >= thr).mean())
            for g, ng in nm.groupby("ancestry"):
                hit = (ng.score >= thr).values.astype(float)
                lo, hi = boot_mean(hit, ng.person_a.values, B=1000)
                rows.append({"set": label, "matcher": matcher, "class": cls, "thr_fmr": target, "ancestry": g,
                             "n_persons": ng.person_a.nunique(), "n_nonmated": len(ng), "FMR": hit.mean(),
                             "FMR_lo": lo, "FMR_hi": hi, "FMR_ratio": hit.mean() / fmr_all if fmr_all > 0 else np.nan,
                             "LR_shift_rel": shifts.get(g, np.nan) - mean_shift, "FNMR_class": fnmr})


def summarise(R):
    out = []
    for (st, m, c, t), d in R.groupby(["set", "matcher", "class", "thr_fmr"]):
        f = d.FMR.replace(0, np.nan)
        out.append({"set": st, "matcher": m, "class": c, "thr_fmr": t,
                    "FMR max/min": f.max() / f.min() if f.min() > 0 else np.inf,
                    "FMR max/median": d.FMR.max() / d.FMR.median() if d.FMR.median() > 0 else np.inf,
                    "LR spread": d.LR_shift_rel.max() - d.LR_shift_rel.min(),
                    "FNMR": d.FNMR_class.iloc[0], "top FMR group": d.loc[d.FMR.idxmax(), "ancestry"]})
    return pd.DataFrame(out)


def main(argv=None):
    p = argparse.ArgumentParser()
    p.add_argument("--flux", required=True)
    p.add_argument("--cache", default="data/cache_gen2")
    p.add_argument("--main-cache", default="data/cache_extended")
    p.add_argument("--models", nargs="+", default=["adaface", "adaface_kprpe", "arcface"])
    p.add_argument("--workers", type=int, default=4)
    a = p.parse_args(argv)
    cache, flux = Path(a.cache), Path(a.flux)
    idx = flux_index(flux, cache)
    es.step_crops_parallel(cache, idx, a.workers)
    EMB_G.mkdir(parents=True, exist_ok=True)
    for f in (ROOT / "data/embeddings_v2").glob("*_channel_order.json"):
        if not (EMB_G / f.name).exists():
            shutil.copy(f, EMB_G / f.name)
    es.EMB2 = EMB_G
    es.step_embed(cache, idx, a.models)

    meta = pd.read_csv(es.SYNTH / "metadata.csv", low_memory=False).drop_duplicates("identity_id").set_index("identity_id")
    attrs = meta[["ancestry", "gender_presentation"]]
    sources = set(idx.source_id)
    kept_sources = set(idx[idx.kept].source_id)
    main_idx = pd.read_csv(Path(a.main_cache) / "image_index.csv")
    main_idx = main_idx[(main_idx.set == "main") & main_idx.identity_id.isin(sources)]
    q_img = pd.DataFrame({"file": main_idx.file, "person": main_idx.identity_id, "condition": main_idx.condition})
    f_img = pd.DataFrame({"file": idx.file, "person": idx.source_id, "condition": idx.condition})
    rows = []
    for subset, keep in [("all", sources), ("kept", kept_sources)]:
        PQ = make_pairs(q_img[q_img.person.isin(keep)], attrs)
        PF = make_pairs(f_img[f_img.person.isin(keep)], attrs)
        es.log(f"{subset}: Qwen {len(PQ)} pairs, FLUX {len(PF)} pairs")
        for name in a.models:
            es.EMB2 = ROOT / "data/embeddings_v2"; mi, ME, mok = es.load_emb(name)
            es.EMB2 = EMB_G; fi, FE, fok = es.load_emb(name)
            analyse(PQ, score(PQ, mi, ME, mok), f"Qwen-{subset}", name, rows)
            analyse(PF, score(PF, fi, FE, fok), f"FLUX-{subset}", name, rows)
            es.log(f"{subset}: {name} done")
    R = pd.DataFrame(rows); R.to_csv(OUT / "gen2_comparison.csv", index=False)
    S = summarise(R); S.to_csv(OUT / "gen2_comparison_summary.csv", index=False)
    md = ["# Generator comparison: Qwen-Image-2512 vs FLUX.2 [klein], same descriptions\n",
          "Same pair design, same recognisers. Threshold at FMR 1e-3 per set/class. LR spread = highest minus lowest "
          "relative LR shift of mated pairs (global vs per-ancestry logistic calibration).\n",
          S.round(3).to_markdown(index=False) if hasattr(S, "to_markdown") else S.round(3).to_string(index=False)]
    for cls in ["cctv_still", "edit_hq"]:
        t = R[(R["class"] == cls) & (R.matcher == a.models[0]) & (R.thr_fmr == 1e-2)].pivot_table(index="ancestry", columns="set", values="FMR_ratio")
        md += [f"\n## {cls}, {a.models[0]}: FMR ratio per ancestry (threshold FMR 1e-2)\n", t.round(2).to_string()]
    (OUT / "gen2_comparison.md").write_text("\n".join(md), encoding="utf-8")
    es.log("gen2 -> results_extended/gen2_comparison.md")


if __name__ == "__main__":
    main()
