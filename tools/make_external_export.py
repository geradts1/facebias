"""
Build the comparison pairs and an export package for System C.

    python tools/make_external_export.py                      # defaults
    python tools/make_external_export.py --meta data/synth1000/metadata.csv --out data/system_c_export

Writes to --out:
  images.csv        image_id, file name, absolute path, identity, condition, role (gallery/probe)
  all_images.txt    absolute paths, one per line (for a batch tool: enrol everything once)
  gallery.txt       the reference photos (1 per identity)
  probes.txt        all other images (ref2, edits, CCTV degradations, video stills)
  pairs.csv         image_a,image_b  (absolute paths; for a tool that takes a pair list)
  pairs_meta.csv    the same pairs plus pair_id, mated, condition and demographics
  README_SYSTEM_C.md  instructions and what to record
Rerun after every finalize: file names are stable, so scores from an earlier run
are reused by import_external_scores.py (matching on file name).
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path, PureWindowsPath

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from facebias.pairs import build_pairs_stratified  # noqa: E402

WIN_ROOT_DEFAULT = None  # default: this checkout (as seen by the machine running the script)

README = """# System C export ({n_img} images, {n_id} identities, {n_pairs} pairs)

Generated by tools/make_external_export.py from `{meta}`.

## Preferred: gallery x probe (complete matrix)
1. Enrol every image in `all_images.txt` once. Keep a list of images that fail
   enrolment (FTE); FTE per group is itself a bias result.
2. Compare `gallery.txt` ({n_gal} references) with `probes.txt` ({n_probe} images)
   = {n_matrix:,} comparisons. Template comparisons are cheap; enrolment is the cost.
3. Export raw similarity scores (no threshold, no rank cut-off), as a long CSV
   `gallery,probe,score` or as a matrix (rows = gallery, columns = probes).

## Alternative: pair list
Have the tool score `pairs.csv` (image_a,image_b) -> `image_a,image_b,score`
(leave score empty for FTE). {n_mated:,} mated + {n_nonmated:,} non-mated pairs,
non-mated stratified per condition ({n_same} same group + {n_cross} other group per reference per condition;
same group = {demo}).

## Record (calibration is version-specific)
- System C SDK / tool version, algorithm/matcher version, configuration file
- enrolment settings (face finder, quality/eye-distance thresholds) and how FTE is reported
- score type (similarity range, e.g. [0,1])
- date, machine

## Import
    python tools/import_external_scores.py --scores <export.csv> [--fte fte.txt]
    python -m facebias.cli evaluate --pairs data/scored_system_c.csv --group ancestry --out results_system_c_ancestry
"""


def main(argv=None):
    p = argparse.ArgumentParser()
    p.add_argument("--meta", default="data/synth1000/metadata.csv")
    p.add_argument("--out", default="data/system_c_export")
    p.add_argument("--win-root", default=WIN_ROOT_DEFAULT,
                   help="folder that metadata paths are relative to, as seen by the System C machine")
    p.add_argument("--n-same", type=int, default=4)
    p.add_argument("--n-cross", type=int, default=2)
    p.add_argument("--demo-cols", nargs="*", default=["gender_presentation", "ancestry"])
    p.add_argument("--seed", type=int, default=0)
    a = p.parse_args(argv)

    meta_path = ROOT / a.meta if not Path(a.meta).is_absolute() else Path(a.meta)
    out = ROOT / a.out if not Path(a.out).is_absolute() else Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    meta = pd.read_csv(meta_path)
    if "excluded" in meta.columns:
        meta = meta[meta.excluded.isna() | (meta.excluded.astype(str).str.lower().isin(["false", "0", ""]))]
    meta["path"] = meta.path.str.replace("/", "\\", regex=False)
    winroot = PureWindowsPath(a.win_root or str(ROOT))
    meta["abs_path"] = [str(winroot / PureWindowsPath(x)) for x in meta.path]
    meta["file"] = [PureWindowsPath(x).name for x in meta.path]
    assert meta.file.is_unique, "file names must be unique (scores are matched on file name)"

    # sanity: do the files exist? (checked relative to this checkout)
    rel = [ROOT / PureWindowsPath(x).as_posix() for x in meta.path.head(200)]
    missing = sum(not r.exists() for r in rel)
    if missing:
        print(f"WARNING: {missing}/200 sampled image files not found under {ROOT}")

    meta["role"] = (meta.condition == "reference").map({True: "gallery", False: "probe"})
    meta = meta.reset_index(drop=True)
    meta.insert(0, "image_id", [f"img{i:06d}" for i in range(len(meta))])
    keep = ["image_id", "file", "abs_path", "path", "identity_id", "role", "condition", "edit"]
    meta[keep].to_csv(out / "images.csv", index=False)
    for name, sel in [("all_images.txt", meta), ("gallery.txt", meta[meta.role == "gallery"]),
                      ("probes.txt", meta[meta.role == "probe"])]:
        (out / name).write_text("\n".join(sel.abs_path) + "\n", encoding="utf-8")

    pairs = build_pairs_stratified(meta, n_same_per_cond=a.n_same, n_cross_per_cond=a.n_cross,
                                   demo_cols=a.demo_cols, seed=a.seed)
    absmap = dict(zip(meta.path, meta.abs_path))
    pd.DataFrame({"image_a": pairs.image_a.map(absmap),
                  "image_b": pairs.image_b.map(absmap)}).to_csv(out / "pairs.csv", index=False)
    pairs.to_csv(out / "pairs_meta.csv", index=False)

    n_gal = int((meta.role == "gallery").sum()); n_probe = len(meta) - n_gal
    (out / "README_SYSTEM_C.md").write_text(README.format(
        n_img=len(meta), n_id=meta.identity_id.nunique(), n_pairs=len(pairs), meta=a.meta,
        n_gal=n_gal, n_probe=n_probe, n_matrix=n_gal * n_probe,
        n_mated=int(pairs.mated.sum()), n_nonmated=int((1 - pairs.mated).sum()),
        n_same=a.n_same, n_cross=a.n_cross, demo=" x ".join(a.demo_cols)), encoding="utf-8")

    print(f"{len(meta)} images ({n_gal} gallery, {n_probe} probes), {meta.identity_id.nunique()} identities")
    print(f"{len(pairs)} pairs: {pairs.mated.sum()} mated, {(1 - pairs.mated).sum()} non-mated -> {out}")
    print(pairs.groupby("condition_b").mated.agg(["sum", "count"]).rename(
        columns={"sum": "mated", "count": "pairs"}).to_string())


if __name__ == "__main__":
    main()
